#Вход: функция получит пустую строку или слова, строковые данные
#Выход: строка с сокращением или пустая
#Структура: строки(str)
#Алгоритм:
#1. создаем функцию в которой сразу убираем лишние пробелы по краям
#2. если после этого текст пустой - возвращаем пустую строку
#3. если текст есть в строке , то текст разделяем сплитом по словам (разбить по сериям пробельных символов) и эти слова помещаем в строку результата
#4. перебираем слова в строке резалт
#5. сюда же помещаем нулевые по индексу буквы увеличеные к верхнему регистру
#6. выводим результат
def make_initials(text):
    text = text.strip()
    if text == "":
        return "Введите текст" #Обработка пустого текста
    words = text.split()
    text2 = ""
    result = ""
    for word in words:
        result += word[0].upper()
        text2 += " "+ word[0].upper() + word[1:]
    return result + "|" + text2
print(make_initials("отдел контроля качества"))  # ОКК | Отдел Контроля Качества
print(make_initials(" "))
print(make_initials(" организация     объединенных наций   "))
print(make_initials("  европейский высший цифровых технологий и предпринимательства"))